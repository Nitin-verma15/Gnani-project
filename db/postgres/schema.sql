-- Munshi on PostgreSQL (for example Neon). Same tables and columns as the app's
-- SQLite database in src/db.js, so the app can be pointed at it later.
-- Money is whole paise (BIGINT). Dates are business-local text: YYYY-MM-DD.
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS business (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  name TEXT, type TEXT, owner_name TEXT,
  phone TEXT, address TEXT, gstin TEXT, upi_id TEXT
);
INSERT INTO business (id) VALUES (1) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT,
  notes TEXT,
  created_at TEXT NOT NULL,
  voided_at TEXT
);

-- One ledger for all money. Balances are always derived from it, never stored.
CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('sale', 'expense', 'payment')),
  customer_id BIGINT REFERENCES customers(id),
  amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
  paid_paise BIGINT NOT NULL DEFAULT 0 CHECK (paid_paise >= 0), -- sales only: received at time of sale
  category TEXT,
  description TEXT,
  method TEXT,
  occurred_on TEXT NOT NULL,
  created_at TEXT NOT NULL,
  voided_at TEXT,
  gst_rate DOUBLE PRECISION
);
CREATE INDEX IF NOT EXISTS idx_tx_date ON transactions(occurred_on);
CREATE INDEX IF NOT EXISTS idx_tx_customer ON transactions(customer_id);

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT REFERENCES customers(id),
  description TEXT NOT NULL,
  amount_paise BIGINT,
  status TEXT NOT NULL DEFAULT 'open',
  due_on TEXT,
  created_at TEXT NOT NULL,
  voided_at TEXT
);

CREATE TABLE IF NOT EXISTS appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT REFERENCES customers(id),
  service TEXT NOT NULL,
  starts_at TEXT NOT NULL, -- YYYY-MM-DDTHH:MM, business-local time
  status TEXT NOT NULL DEFAULT 'booked',
  created_at TEXT NOT NULL,
  voided_at TEXT
);

CREATE TABLE IF NOT EXISTS notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text TEXT NOT NULL,
  created_at TEXT NOT NULL,
  voided_at TEXT
);

-- Every write the assistant makes, with how to reverse it.
CREATE TABLE IF NOT EXISTS actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  summary TEXT NOT NULL,
  undo_ops TEXT NOT NULL,
  created_at TEXT NOT NULL,
  undone_at TEXT,
  undo_seen INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS threads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day TEXT NOT NULL,
  created_at TEXT NOT NULL,
  provider TEXT NOT NULL DEFAULT 'anthropic'
);
CREATE TABLE IF NOT EXISTS thread_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id BIGINT NOT NULL REFERENCES threads(id),
  role TEXT NOT NULL,
  content TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL,
  text TEXT NOT NULL,
  action_ids TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL,
  links TEXT NOT NULL DEFAULT '[]'
);

-- Stock on hand is never stored: it is the sum of the movements.
CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  unit TEXT NOT NULL DEFAULT 'pcs',
  price_paise BIGINT,
  low_at DOUBLE PRECISION,
  created_at TEXT NOT NULL,
  voided_at TEXT
);
CREATE TABLE IF NOT EXISTS stock_moves (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES items(id),
  qty DOUBLE PRECISION NOT NULL CHECK (qty <> 0), -- positive in, negative out
  reason TEXT NOT NULL,
  transaction_id BIGINT REFERENCES transactions(id),
  created_at TEXT NOT NULL,
  voided_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_moves_item ON stock_moves(item_id);
CREATE INDEX IF NOT EXISTS idx_moves_tx ON stock_moves(transaction_id);

-- Ready-made views, handy for showing the data. Amounts here are in rupees.
CREATE OR REPLACE VIEW customer_balances AS
SELECT c.id, c.name, c.phone,
       round(COALESCE(SUM(CASE t.kind WHEN 'sale' THEN t.amount_paise - t.paid_paise
                                      WHEN 'payment' THEN -t.amount_paise ELSE 0 END), 0) / 100.0, 2) AS owes,
       round(COALESCE(SUM(CASE WHEN t.kind = 'sale' THEN t.amount_paise END), 0) / 100.0, 2) AS total_spent,
       MAX(t.occurred_on) AS last_activity
  FROM customers c
  LEFT JOIN transactions t ON t.customer_id = c.id AND t.voided_at IS NULL
 WHERE c.voided_at IS NULL
 GROUP BY c.id;

CREATE OR REPLACE VIEW stock_on_hand AS
SELECT i.id, i.name, i.unit, round(i.price_paise / 100.0, 2) AS price, i.low_at,
       COALESCE(SUM(m.qty), 0) AS on_hand,
       COALESCE(SUM(m.qty), 0) <= COALESCE(i.low_at, 0) AS is_low
  FROM items i
  LEFT JOIN stock_moves m ON m.item_id = i.id AND m.voided_at IS NULL
 WHERE i.voided_at IS NULL
 GROUP BY i.id;

CREATE OR REPLACE VIEW daily_totals AS
SELECT occurred_on AS day,
       round(COALESCE(SUM(CASE WHEN kind = 'sale' THEN amount_paise END), 0) / 100.0, 2) AS sales,
       round(COALESCE(SUM(CASE WHEN kind = 'expense' THEN amount_paise END), 0) / 100.0, 2) AS expenses,
       round(COALESCE(SUM(CASE WHEN kind = 'sale' THEN amount_paise - paid_paise END), 0) / 100.0, 2) AS udhaar_given,
       round(COALESCE(SUM(CASE WHEN kind = 'payment' THEN amount_paise END), 0) / 100.0, 2) AS udhaar_collected,
       COUNT(*) FILTER (WHERE kind = 'sale') AS number_of_sales
  FROM transactions
 WHERE voided_at IS NULL
 GROUP BY occurred_on;
